#!/usr/bin/env python3
"""Supplementary compute table from the committed SLURM-accounting aggregate
(tallies/compute_accounting.json, produced from `sacct` over the campaign
window). Emits paper/tables/table_compute.tex; no hand-edited cells.

Usage: python -m experiments.exp_anatomy.make_compute_table [out_dir]
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER_TABLES = HERE.parents[2] / "paper" / "tables"

ROWS = [  # (key, display label)
    ("datagen",   "Data generation (walk rendering, layouts, objects)"),
    ("refext",    "Reference-feature extraction (5 frozen models)"),
    ("shakedown", "Shakedown waves (2-seed matrix, diagnostics)"),
    ("eth3d",     "ETH3D objective matrix (bulk, 3 seeds)"),
    ("scannet",   "ScanNet objective matrix (bulk, 3 seeds)"),
    ("replica",   "Replica objective matrix (bulk, 3 seeds)"),
    ("encoders",  "Encoder checkpoints (incl.\\ 5k/15k curves)"),
    ("sweeps",    "Robustness sweeps (horizon, head capacity, curves, controls)"),
    ("interv",    "Mechanism intervention"),
    ("modality",  "Conditioning-target (modality) matrix"),
    ("pilots",    "Pilots and harness checks"),
]


def main():
    out_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else PAPER_TABLES
    d = json.load(open(HERE / "tallies" / "compute_accounting.json"))
    lines = [
        "% AUTO-GENERATED by experiments/exp_anatomy/make_compute_table.py -- do not edit.",
        "\\begin{table}[h]", "\\centering\\small",
        "\\caption{Compute accounting for every experiment in this paper "
        "(SLURM \\texttt{sacct}, wall-clock $\\times$ allocated GPUs). All jobs "
        "are single-GPU (RTX~4090 or A100~80GB) or CPU-only (data generation); "
        "host memory is the per-wave peak resident set.}",
        "\\label{tab:compute}",
        "\\begin{tabular}{lrrrr}", "\\toprule",
        "wave & jobs & 4090\\,h & A100\\,h & peak mem\\\\", "\\midrule",
    ]
    for key, disp in ROWS:
        v = d.get(key)
        if not v:
            continue
        lines.append(f"{disp} & {v['jobs']} & {v['gpuh_4090']:.0f} & "
                     f"{v['gpuh_a100']:.0f} & {v['maxrss_gb']:.0f}\\,GB \\\\")
    t = d["TOTAL"]
    lines += ["\\midrule",
              f"\\textbf{{Total}} & \\textbf{{{t['jobs']}}} & "
              f"\\textbf{{{t['gpuh_4090']:.0f}}} & \\textbf{{{t['gpuh_a100']:.0f}}} & "
              f"--- \\\\",
              "\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "table_compute.tex").write_text("\n".join(lines))
    print(f"wrote {out_dir / 'table_compute.tex'} "
          f"(total {t['gpuh_4090'] + t['gpuh_a100']:.0f} GPU-h, {t['jobs']} jobs)")


if __name__ == "__main__":
    main()
