#!/usr/bin/env python3
"""Generate the capability-matrix LaTeX tables from a committed tally JSONL.

Follows the group convention (cf. neurips_2026/0_FeatureEngineering): result
loaders -> aggregation -> a standalone ``\\begin{table}..\\end{table}`` fragment
written to ``paper/tables/``. The paper ``\\input``s these; no cell is ever hand
edited. Re-run after a new tally to refresh every number.

Usage:
    python -m experiments.exp_anatomy.make_tables            # both datasets
    python -m experiments.exp_anatomy.make_tables <out_dir>  # override target
"""
import json
import statistics
import sys
from collections import defaultdict
from pathlib import Path

EXPECTED_SEEDS = 3

HERE = Path(__file__).resolve().parent
PAPER_TABLES = HERE.parents[2] / "paper" / "tables"  # spatial_reasoning/paper/tables

# probe -> (metric direction, header). direction: +1 higher-better, -1 lower-better
COLS = [
    ("placerec", +1, "place$\\uparrow$"),
    ("depthprobe", -1, "depth$\\downarrow$"),
    ("rollout", +1, "roll$\\uparrow$"),
    ("navdist", +1, "nav$\\uparrow$"),
    ("relpose", +1, "pose$\\uparrow$"),
]
# row order + display labels
ROWS = [
    ("scratch", "scratch"),
    ("rgb_only", "rgb-only"),
    ("recon", "recon"),
    ("symalign", "sym-align"),
    ("contrastive", "contrastive"),
    ("jepa", "jepa"),
    ("fuse_cj_25", "fuse\\,$\\lambda$.25"),
    ("fuse_cj_50", "fuse\\,$\\lambda$.50"),
    ("fuse_cj_75", "fuse\\,$\\lambda$.75"),
]
REF_ROW = ("ref:dinov2b", "DINOv2-B (ref)")
# rows eligible for the per-column bold (exclude the random and frozen-ref rows)
BOLD_ELIGIBLE = {r for r, _ in ROWS if r != "scratch"}


def load_means(tally_path):
    """channel 'probe:row' -> (mean, std, n) of primary over seeds, ok rows only.

    Guards against the two silent failure modes we actually hit: duplicate
    (channel, seed) results (a stray result dir double-counted) and missing
    seeds (failed jobs leaving a cell at n<EXPECTED_SEEDS).
    """
    acc = defaultdict(dict)  # channel -> {seed: primary}
    for line in Path(tally_path).read_text().splitlines():
        if not line.strip():
            continue
        r = json.loads(line)
        ch, p = r.get("channel"), r.get("primary")
        if r.get("status") != "ok" or ch is None or p is None:
            continue
        if ch.count(":") and ch.split(":", 1)[0] in {c for c, _, _ in COLS}:
            seed = r.get("metrics", {}).get("seed")
            if seed in acc[ch]:
                print(f"WARNING {tally_path.name}: duplicate (channel={ch}, "
                      f"seed={seed}) — keeping first, check the results dir")
                continue
            acc[ch][seed] = float(p)
    out = {}
    for ch, by_seed in acc.items():
        v = list(by_seed.values())
        if len(v) != EXPECTED_SEEDS:
            print(f"WARNING {tally_path.name}: {ch} has n={len(v)} seeds "
                  f"(expected {EXPECTED_SEEDS}) — cell marked, rerun missing jobs")
        out[ch] = (statistics.mean(v),
                   statistics.stdev(v) if len(v) > 1 else 0.0, len(v))
    return out


def fmt(v):
    """0.852 -> '.852'; -0.093 -> '$-$.093'; 1.06 -> '1.06'."""
    s = f"{abs(v):.3f}" if abs(v) < 1 else f"{abs(v):.2f}"
    if abs(v) < 1:
        s = s[1:]  # strip leading 0
    return ("$-$" if v < 0 else "") + s


def fmt_std(s):
    """std as a compact subscript: 0.010 -> '.01'; 0.424 -> '.42'."""
    return f"{s:.2f}"[1:] if s < 1 else f"{s:.1f}"


def build(tally_path, caption, label):
    means = load_means(tally_path)
    # best (bold) value per column among eligible rows
    best = {}
    for probe, direction, _ in COLS:
        cand = [(means[f"{probe}:{r}"][0], r) for r, _ in ROWS
                if r in BOLD_ELIGIBLE and f"{probe}:{r}" in means]
        if cand:
            best[probe] = (max if direction > 0 else min)(cand)[1]

    def cell(probe, row):
        key = f"{probe}:{row}"
        if key not in means:
            return "--"
        m, s, n = means[key]
        txt = f"{fmt(m)}$_{{\\pm{fmt_std(s)}}}$"
        if n != EXPECTED_SEEDS:
            txt += f"$^{{(n{n})}}$"  # visible flag until the gap-fill lands
        return f"\\textbf{{{txt}}}" if best.get(probe) == row else txt

    lines = [
        "% AUTO-GENERATED by experiments/exp_anatomy/make_tables.py -- do not edit.",
        "\\begin{table}[t]",
        "\\centering\\small",
        "\\setlength{\\tabcolsep}{4.5pt}",
        f"\\caption{{{caption}}}",
        f"\\label{{{label}}}",
        "\\begin{tabular}{lccccc}",
        "\\toprule",
        "row & " + " & ".join(h for _, _, h in COLS) + "\\\\",
        "\\midrule",
    ]
    for row, disp in ROWS:
        lines.append(disp + " & " + " & ".join(cell(p, row) for p, _, _ in COLS) + " \\\\")
    lines.append("\\midrule")
    rr, rdisp = REF_ROW
    lines.append(rdisp + " & " + " & ".join(cell(p, rr) for p, _, _ in COLS) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def build_modality(tally_path, caption, label):
    """Replica modality matrix: rows (lam, target-modality), same 5 columns."""
    means = load_means(tally_path)
    mods = [("pcd", "pcd graph"), ("depth", "depth map"),
            ("layout", "2D layout"), ("objgraph", "object graph")]
    lines = [
        "% AUTO-GENERATED by experiments/exp_anatomy/make_tables.py -- do not edit.",
        "\\begin{table}[t]", "\\centering\\small",
        "\\setlength{\\tabcolsep}{3.5pt}",
        f"\\caption{{{caption}}}", f"\\label{{{label}}}",
        "\\begin{tabular}{llccccc}", "\\toprule",
        "$\\lambda$ & target & " + " & ".join(h for _, _, h in COLS) + "\\\\",
    ]
    for lam, lamdisp in [(100, "$1$ (InfoNCE)"), (0, "$0$ (JEPA)")]:
        lines.append("\\midrule")
        # bold best modality per column within this lambda block
        best = {}
        for probe, direction, _ in COLS:
            cand = [(means[f"{probe}:cj{lam}@{m}"][0], m) for m, _ in mods
                    if f"{probe}:cj{lam}@{m}" in means]
            if cand:
                best[probe] = (max if direction > 0 else min)(cand)[1]
        for k, (m, disp) in enumerate(mods):
            cells = []
            for probe, _, _ in COLS:
                key = f"{probe}:cj{lam}@{m}"
                if key not in means:
                    cells.append("--"); continue
                mu, sd, n = means[key]
                txt = f"{fmt(mu)}$_{{\\pm{fmt_std(sd)}}}$"
                cells.append(f"\\textbf{{{txt}}}" if best.get(probe) == m else txt)
            lines.append((lamdisp if k == 0 else "") + " & " + disp + " & "
                         + " & ".join(cells) + " \\\\")
    lines += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]
    return "\n".join(lines)


def main():
    out_dir = Path(sys.argv[1]) if len(sys.argv) > 1 else PAPER_TABLES
    out_dir.mkdir(parents=True, exist_ok=True)
    mod_tally = HERE / "tallies" / "anatomy_replica_mod.jsonl"
    if mod_tally.exists():
        (out_dir / "table_matrix_modality.tex").write_text(build_modality(
            mod_tally,
            "Conditioning-target (modality) matrix on Replica (12 multi-room "
            "scenes, 3 seeds), at the two objective poles. Same columns and "
            "conventions as Table~\\ref{tab:matrix}. \\textbf{Bold} = best "
            "target per column within each $\\lambda$ block.",
            "tab:modality"))
        print(f"wrote {out_dir / 'table_matrix_modality.tex'}")
    specs = [
        (HERE / "eth3d_bulk_tally.jsonl", "table_matrix_eth3d",
         "ETH3D capability matrix (bulk, 3 seeds). Columns: place-rec (acc), "
         "depth (AbsRel), rollout ($\\Delta R^2$), nav-dist ($R^2$), rel-pose "
         "(dir-cos). $\\uparrow$/$\\downarrow$ = higher/lower better. "
         "\\textbf{Bold} = best trained row per column.", "tab:matrix"),
        (HERE / "scannet_bulk_tally.jsonl", "table_matrix_scannet",
         "ScanNet generality matrix (20 scenes, bulk, 3 seeds). Same columns and "
         "conventions as Table~\\ref{tab:matrix}. The place-rec/rollout/depth "
         "dissociation reproduces; nav-dist/rel-pose are near floor on the small "
         "ScanNet rooms. \\textbf{Bold} = best trained row per column.",
         "tab:matrix_scannet"),
    ]
    for tally, stem, caption, label in specs:
        if not tally.exists():
            print(f"skip {stem}: {tally} missing")
            continue
        (out_dir / f"{stem}.tex").write_text(build(tally, caption, label))
        print(f"wrote {out_dir / (stem + '.tex')}")


if __name__ == "__main__":
    main()
